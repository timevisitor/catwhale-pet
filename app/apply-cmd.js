// apply.cmd 生成器（规格 §6）
//
// 纯函数：输入参数 → { cmd: 脚本文本, env: 传给 spawn 的环境变量 }。不碰磁盘、不 require electron。
//
// ── 三条实测出来的硬约束（都是在这个项目里踩出来的）──
// 1) 脚本正文必须**纯 ASCII**。cmd.exe 解析批处理按字节跟踪读取位置，脚本里一旦有多字节字符
//    （中文路径/中文注释），解析就会错位：实测一个 3.5 KB、含 40 行中文 rem 的脚本开始把注释
//    片段当命令执行（'过' is not recognized as an internal or external command）。
// 2) 应用是用 `detached + windowsHide + stdio:'ignore'` spawn 的，**没有控制台**。没有控制台的
//    cmd 里：`chcp` 静默失败；`tasklist` 输出为空（一行都没有）；`findstr` 也无输出；
//    **任何管道（`a | b`）都会永久挂住**（实测 `echo x | findstr x` 都挂）。
//    所以脚本里不许出现管道，也不许指望 tasklist / findstr。
// 3) 中文路径不能写进脚本文件（见 1），也不能靠 `set /p` 读文件（chcp 失效 → 按 ANSI 代码页
//    解释 UTF-8 字节 → 路径变乱码）。做法：由父进程用**环境变量**传给子进程 —— CreateProcess
//    传的是 UTF-16，cmd 拿到的环境变量就是 Unicode 的，%VAR% 展开后 move/ren/start 全正常。
//
// ── 因此「等旧进程退出」这件事用 move 重试来实现 ──
// Windows 上目录里只要有进程占着（正在运行的 exe 被映射、或有进程把它当 CWD），`move` 一定失败。
// 所以「备份」这一步本身就是最可靠的退出判定：重试到成功为止（最多 60 秒），比 tasklist 判 PID
// 更贴近真正要满足的条件（能安全搬走）。`ren` 不能用来判「是否在运行」—— 实测重命名一个正在
// 运行的 exe 是允许的。
//
// last-result.json 里只放纯 ASCII（版本号/结果/unix 秒/日志文件名）：cmd 重定向按当前代码页写字，
// 塞中文会变 GBK，读端按 UTF-8 解析就废。
'use strict';

function pad(n, width = 2) {
  return String(n).padStart(width, '0');
}

/** 20261127-171234（本地时间，用于文件名与日志） */
function stamp(d = new Date()) {
  return `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}-${pad(d.getHours())}${pad(d.getMinutes())}${pad(d.getSeconds())}`;
}

/** 判断一个参数是否需要加引号（含空格/非 ASCII 一律加，最稳） */
function quoteArg(a) {
  const s = String(a == null ? '' : a);
  if (!s) return '""';
  if (/^[^\s"]+$/.test(s) && !/[^\x00-\x7F]/.test(s)) return s;
  return '"' + s.replace(/"/g, '') + '"';
}

/** cmd 里 set 的值：set "VAR=value" 形式（值里不能有裸引号） */
function setLine(name, value) {
  return `set "${name}=${String(value == null ? '' : value).replace(/"/g, '')}"`;
}

/**
 * 生成升级脚本。
 * @param {Object} p
 * @param {string} p.installDir  安装目录绝对路径（可含中文 → 走环境变量）
 * @param {string} p.stageDir    staging 目录（内容就是包根）
 * @param {string} p.exeName     主 exe 文件名，如 桌宠.exe
 * @param {number} p.pid         当前进程 pid（只写进日志与 JSON，用来事后对账）
 * @param {string} p.backupDir   备份目录（<install>.bak-<ts>）
 * @param {string} p.updateDir   更新目录（脚本所在目录，脚本里用 %~dp0 表示）
 * @param {string} p.logName     apply-<ts>.log
 * @param {string} p.fromVersion
 * @param {string} p.toVersion
 * @param {string[]} [p.relaunchArgs] 重启时带上的原命令行参数
 * @param {number} [p.atUnix]    生成时刻的 unix 秒（写进 last-result.json 的 at）
 * @returns {{cmd:string, env:Object<string,string>}}  env 必须原样传给 spawn
 */
function buildApplyCmd(p) {
  const o = p || {};
  const install = String(o.installDir || '');
  const stage = String(o.stageDir || '');
  const exe = String(o.exeName || '');
  const pid = Number(o.pid) || 0;
  const bak = String(o.backupDir || '');
  const updateDir = String(o.updateDir || '');
  const logName = String(o.logName || 'apply.log');
  const from = String(o.fromVersion || '');
  const to = String(o.toVersion || '');
  const at = Number.isFinite(o.atUnix) ? Math.floor(o.atUnix) : Math.floor(Date.now() / 1000);
  const args = (Array.isArray(o.relaunchArgs) ? o.relaunchArgs : []).map(quoteArg).join(' ');

  if (!install || !stage || !exe || !bak || !updateDir) {
    throw new Error('buildApplyCmd: installDir/stageDir/exeName/backupDir/updateDir 都是必填');
  }
  if (!/^[0-9A-Za-z._-]+\.log$/.test(logName)) throw new Error('buildApplyCmd: logName 必须是纯 ASCII 文件名');

  // 传给 spawn 的环境变量（CreateProcess 走 UTF-16，中文路径不经过任何代码页）
  const env = { CW_INSTALL: install, CW_STAGE: stage, CW_EXE: exe, CW_BAK: bak, CW_ARGS: args };

  const L = [];
  L.push('@echo off');
  L.push('chcp 65001 >nul');
  L.push('setlocal enabledelayedexpansion');
  L.push('rem ================================================================');
  L.push('rem catwhale-pet online upgrade script (generated by the app)');
  L.push('rem protocol: shared update spec section 6.');
  L.push('rem ASCII ONLY. No pipes. No tasklist/findstr/chcp dependency:');
  L.push('rem this script runs detached without a console, where those either');
  L.push('rem print nothing or hang forever. Chinese paths arrive through the');
  L.push('rem CW_* environment variables set by the parent process.');
  L.push('rem flow: check staging -> backup(=wait for exit) -> swap -> start');
  L.push('rem       -> write result -> clean up');
  L.push('rem ================================================================');
  // 铁律：CWD 必须离开安装目录，否则 move 会把目标目录锁住
  L.push('cd /d "%~dp0" 2>nul');
  L.push(setLine('LOGNAME', logName));
  L.push('set "LOG=%~dp0' + logName + '"');
  L.push('set "RESULT=%~dp0last-result.json"');
  L.push(setLine('PID', pid));
  L.push(setLine('FROM', from));
  L.push(setLine('TO', to));
  L.push(setLine('AT', at));
  L.push('set "INSTALL=%CW_INSTALL%"');
  L.push('set "STAGE=%CW_STAGE%"');
  L.push('set "EXE=%CW_EXE%"');
  L.push('set "BAK=%CW_BAK%"');
  L.push('set "ARGS=%CW_ARGS%"');
  L.push('set "STEP=0"');
  L.push('call :LOG "START from=%FROM% to=%TO% pid=%PID%"');
  L.push('call :LOG "CWD=%CD%"');
  L.push('call :LOG "INSTALL=%INSTALL%"');
  L.push('call :LOG "STAGE=%STAGE%"');
  L.push('call :LOG "BAK=%BAK%"');
  L.push('call :LOG "EXE=%EXE%"');
  L.push('');
  // ---- 0. staging 里必须有主程序（刚解包的 250 MB exe 可能被 Defender 短暂挡住 → 重试 10 秒）----
  L.push('rem ---- 0. staging must contain the main exe (retry 10s: AV scans new files) ----');
  L.push(':CHECK_STAGE');
  L.push('if exist "%STAGE%\\%EXE%" goto STAGE_OK');
  L.push('set /a STEP+=1');
  L.push('if !STEP! GEQ 10 (');
  L.push('  call :LOG "staging has no main exe after 10s, abort"');
  L.push('  call :LOG "STAGE=%STAGE% EXE=%EXE%"');
  L.push('  goto FAILED');
  L.push(')');
  L.push('call :SLEEP');
  L.push('goto CHECK_STAGE');
  L.push(':STAGE_OK');
  L.push('call :LOG "staging looks good (ticks=!STEP!)"');
  L.push('set "STEP=0"');
  L.push('');
  // ---- 1+2. 等旧进程退出/文件解锁 + 备份：move 成功即代表旧实例已完全放手 ----
  L.push('rem ---- 1+2. backup the install dir; move only succeeds once the old');
  L.push('rem         instance has really let go (running exe mapped / dir as CWD) ----');
  L.push(':BACKUP');
  L.push('move "%INSTALL%" "%BAK%" >nul 2>&1');
  L.push('if not errorlevel 1 goto BACKUP_DONE');
  L.push('set /a STEP+=1');
  L.push('if !STEP! GEQ 60 (');
  L.push('  call :LOG "backup failed after 60s: install dir still in use, left untouched"');
  L.push('  goto FAILED');
  L.push(')');
  L.push('call :SLEEP');
  L.push('goto BACKUP');
  L.push(':BACKUP_DONE');
  L.push('call :LOG "old dir moved to %BAK% (waited !STEP! ticks)"');
  L.push('');
  // ---- 3. 换入 ----
  L.push('rem ---- 3. swap in the new dir (on failure: rollback + restart old) ----');
  L.push('move "%STAGE%" "%INSTALL%" >nul 2>&1');
  L.push('if not errorlevel 1 goto SWAP_DONE');
  L.push('call :LOG "swap failed, rollback"');
  L.push('move "%BAK%" "%INSTALL%" >nul 2>&1');
  L.push('if errorlevel 1 (');
  L.push('  call :LOG "ROLLBACK FAILED, old dir kept at %BAK%"');
  L.push(') else (');
  L.push('  call :LOG "rolled back to the old version"');
  L.push(')');
  L.push('call :WRITE_RESULT failed swap-failed');
  L.push('set "STEP=0"');
  L.push('goto START_OLD');
  L.push(':SWAP_DONE');
  L.push('call :LOG "new dir is in place"');
  L.push('');
  // ---- 4. 启动新版 ----
  L.push('rem ---- 4. start the new version (start exit code decides, up to 5 tries) ----');
  L.push('set "STEP=0"');
  L.push(':START_NEW');
  L.push('start "" "%INSTALL%\\%EXE%" %ARGS%');
  L.push('if not errorlevel 1 goto STARTED');
  L.push('set /a STEP+=1');
  L.push('call :LOG "start returned an error, retry (try !STEP!)"');
  L.push('if !STEP! GEQ 5 (');
  L.push('  call :LOG "new version did not start (5 tries), rolling back"');
  L.push('  goto ROLLBACK_START');
  L.push(')');
  L.push('call :SLEEP');
  L.push('goto START_NEW');
  L.push(':STARTED');
  L.push('call :SLEEP');
  L.push('call :LOG "new version launched"');
  L.push('call :WRITE_RESULT ok ""');
  L.push('call :CLEANUP_BAK');
  L.push('goto DONE');
  L.push('');
  L.push(':ROLLBACK_START');
  L.push('move "%INSTALL%" "%BAK%.new" >nul 2>&1');
  L.push('move "%BAK%" "%INSTALL%" >nul 2>&1');
  L.push('if errorlevel 1 (');
  L.push('  call :LOG "ROLLBACK FAILED: old at %BAK%, new at %BAK%.new"');
  L.push(') else (');
  L.push('  call :LOG "rolled back to the old version"');
  L.push(')');
  L.push('call :WRITE_RESULT failed start-failed');
  L.push('set "STEP=0"');
  L.push(':START_OLD');
  L.push('if not exist "%INSTALL%\\%EXE%" goto DONE');
  L.push('start "" "%INSTALL%\\%EXE%" %ARGS%');
  L.push('if not errorlevel 1 goto DONE');
  L.push('set /a STEP+=1');
  L.push('if !STEP! GEQ 5 goto DONE');
  L.push('call :SLEEP');
  L.push('goto START_OLD');
  L.push('');
  L.push(':FAILED');
  L.push('call :WRITE_RESULT failed wait-or-move-failed');
  L.push('goto DONE');
  L.push('');
  // ---- 子程序 ----
  L.push('rem ---- subroutines ----');
  L.push(':WRITE_RESULT');
  L.push('> "%RESULT%" echo {"from":"%FROM%","to":"%TO%","result":"%~1","at":%AT%,"log":"%LOGNAME%","logPath":"%LOGNAME%","error":"%~2"}');
  L.push('call :LOG "result written result=%~1 error=%~2"');
  L.push('exit /b 0');
  L.push('');
  L.push(':CLEANUP_BAK');
  L.push('rmdir /s /q "%BAK%" >nul 2>&1');
  L.push('if exist "%BAK%" (');
  L.push('  call :LOG "old dir could not be removed, kept: %BAK%"');
  L.push(') else (');
  L.push('  call :LOG "old dir cleaned"');
  L.push(')');
  L.push('exit /b 0');
  L.push('');
  L.push(':SLEEP');
  L.push('ping -n 2 127.0.0.1 >nul');
  L.push('exit /b 0');
  L.push('');
  L.push(':LOG');
  L.push('>>"%LOG%" echo [%DATE% %TIME%] %~1');
  L.push('exit /b 0');
  L.push('');
  L.push(':DONE');
  L.push('call :LOG "script done"');
  L.push('exit /b 0');
  const cmd = L.join('\r\n') + '\r\n';

  // 生成时自检：这三条是硬约束，破了就会静默失效
  const bad = cmd.match(/[^\x00-\x7F]/);
  if (bad) {
    throw new Error(`buildApplyCmd: 脚本里出现非 ASCII 字符「${bad[0]}」—— cmd 解析会错位`);
  }
  const pipeLine = L.find((l) => l.includes('|'));
  if (pipeLine) throw new Error('buildApplyCmd: 脚本里不许出现管道（无控制台会永久挂住）：' + pipeLine);
  const codeLine = L.find((l) => /tasklist|findstr/i.test(l) && !/^rem /.test(l));
  if (codeLine) throw new Error('buildApplyCmd: 无控制台时 tasklist/findstr 不产出任何输出，不许依赖它们：' + codeLine);
  return { cmd, env };
}

module.exports = { buildApplyCmd, stamp, quoteArg };
